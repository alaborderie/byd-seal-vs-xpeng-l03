import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
await page.goto(process.argv[2] ?? 'http://localhost:8519', { waitUntil: 'networkidle' })
await page.locator('#match').scrollIntoViewIfNeeded()
const score = () => page.locator('#match p[aria-live]').innerText()
const before = await score()
await page.getByRole('radio', { name: 'Excellence' }).check({ force: true })
await page.getByRole('radio', { name: 'Perf. Ultra' }).check({ force: true })
await page.waitForTimeout(400)
const after = await score()
const sprint = await page.locator('#match li', { hasText: '0 à 100 km/h' }).innerText()
await page.locator('#road-trip').scrollIntoViewIfNeeded()
await page.getByRole('radio', { name: /Nantes/ }).check({ force: true })
await page.waitForTimeout(300)
const nantes = await page.locator('#road-trip p[aria-live]').innerText()
await page.getByRole('radio', { name: /Nice/ }).check({ force: true })
await page.waitForTimeout(300)
const nice = await page.locator('#road-trip p[aria-live]').innerText()
await page.locator('#performances').scrollIntoViewIfNeeded()
await page.waitForTimeout(6000)
const clocks = await page.locator('#performances p.font-display.text-2xl').allInnerTexts()
console.log(JSON.stringify({ before, after, sprint: sprint.replace(/\s+/g, ' '), nantes, nice, clocks, errors }, null, 1))
await browser.close()
